class Assignment_Operators{
    public static void main(String[] args) {
        int a=10;
      System.out.println("--------------------------------Assignment Operators----------------------------------");
        
         System.out.println("a+=5 :"+(a+=5)); 
        System.out.println("a-=5 :"+(a-=5));
        System.out.println("a*=5 :"+(a*=10));
        System.out.println("a/=5 :"+(a/=10));
        System.out.println("a%=5 :"+(a%=10));
    }
    

}